    TP_EMAIL         VARCHAR(50),
    PERIOD_KIND      VARCHAR(1)   NOT NULL,               -- kieuKy Q/M
    FROM_DT          DATE         NOT NULL,               -- kyKKhaiTuNgay
    TO_DT            DATE         NOT NULL,               -- kyKKhaiDenNgay
    OFFICE_CODE      VARCHAR(10)  NOT NULL,               -- maCQTNoiNop
    OFFICE_NAME      VARCHAR(150) NOT NULL,               -- tenCQTNoiNop
    DECL_DT          DATE         NOT NULL,               -- ngayLapTKhai
    EXT_REASON_CODE  VARCHAR(10),
    EXT_REASON       VARCHAR(255),
    AGENT_NAME       VARCHAR(400),                        -- [06]
    AGENT_TAX_CODE   VARCHAR(14),                         -- [07]
    AGENT_CTR_NO     VARCHAR(100),                        -- [08]

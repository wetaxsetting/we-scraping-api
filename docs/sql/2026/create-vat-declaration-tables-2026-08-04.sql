    ACTIVITY_NAME    VARCHAR(150) NOT NULL,               -- [01a] ten_NganhNghe
    ACTIVITY_CODE    VARCHAR(2)   NOT NULL,               -- ma_NganhNghe
    ACCT_ITEM        VARCHAR(10)  NOT NULL,               -- tieuMucHachToan (1701)
    PERIOD           VARCHAR(10)  NOT NULL,               -- [01b] kyKKhai
    SUPPL_NO         INTEGER      NOT NULL DEFAULT 0,     -- [02] soLan
    DECL_TYPE        VARCHAR(1)   NOT NULL DEFAULT 'C',   -- [03] C/B
    TP_NAME          VARCHAR(400) NOT NULL,               -- [04] tenNNT
    TP_TAX_CODE      VARCHAR(14)  NOT NULL,               -- [05] mst
    TP_ADDR          VARCHAR(255),
    TP_WARD          VARCHAR(255),
    TP_WARD_CODE     VARCHAR(255),
    TP_DIST          VARCHAR(255),

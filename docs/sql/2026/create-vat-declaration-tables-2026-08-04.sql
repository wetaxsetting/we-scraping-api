    DU_PROV_CODE     VARCHAR(255),                        -- [11c]
    DU_PROV          VARCHAR(255),
    DU_DIST_CODE     VARCHAR(255),                        -- [11b]
    DU_DIST          VARCHAR(255),
    DU_WARD_CODE     VARCHAR(255),                        -- [11a]
    DU_WARD          VARCHAR(255),
    INDICATORS       JSONB        NOT NULL DEFAULT '{}'::jsonb,
    REG_ID           VARCHAR(100),
    REG_DTM          VARCHAR(14)  NOT NULL,
    MOD_ID           VARCHAR(100),
    MOD_DTM          VARCHAR(14)  NOT NULL,

-- ============================================================================
-- VAT Declaration (Add-on > Tax Report) — TAX_DECLARATIONS + TAX_DECLARATION_ITEMS
-- Target: wecmsdevdb (shared refactor dev DB). Idempotent (IF NOT EXISTS).
-- Matches entities: domain/vatdeclaration/entity/VatDeclaration(Indicator).java
-- Design source: PO sheet 2026-07-15 rev (ct40a = VAT_PAYABLE_ACTIVITY,
--                ct40 = VAT_PAYABLE_NET; PK/FK unified as BIGINT IDENTITY).
-- NOTE: TAX_DECLARATION_ADJUSTMENTS (VAT_DECL_ADJ, 01-1/KHBS) chưa có spec cột
--       — bổ sung sau khi PO chốt.
-- ============================================================================

CREATE TABLE IF NOT EXISTS TAX_DECLARATIONS (
    SID              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    BIZ_KEY          VARCHAR(20)  NOT NULL,
    PERIOD_TYPE      VARCHAR(10)  NOT NULL,               -- 'month' | 'quarter'
    PERIOD_VALUE     INTEGER      NOT NULL,               -- 1..12 | 1..4
    PERIOD_YEAR      INTEGER      NOT NULL,
    FORM_CODE        VARCHAR(3)   NOT NULL,               -- maTKhai (842)
    XML_VER          VARCHAR(10)  NOT NULL,               -- pbanTKhaiXML (2.6.8)
    ACTIVITY_NAME    VARCHAR(150) NOT NULL,               -- [01a] ten_NganhNghe
    ACTIVITY_CODE    VARCHAR(2)   NOT NULL,               -- ma_NganhNghe
    ACCT_ITEM        VARCHAR(10)  NOT NULL,               -- tieuMucHachToan (1701)
    PERIOD           VARCHAR(10)  NOT NULL,               -- [01b] kyKKhai
    SUPPL_NO         INTEGER      NOT NULL DEFAULT 0,     -- [02] soLan
    DECL_TYPE        VARCHAR(1)   NOT NULL DEFAULT 'C',   -- [03] C/B
    TP_NAME          VARCHAR(400) NOT NULL,               -- [04] tenNNT
    TP_TAX_CODE      VARCHAR(14)  NOT NULL,               -- [05] mst
    TP_ADDR          VARCHAR(255),
    TP_WARD          VARCHAR(255),
    TP_WARD_CODE     VARCHAR(255),
    TP_DIST          VARCHAR(255),
    TP_DIST_CODE     VARCHAR(255),
    TP_PROV          VARCHAR(200) NOT NULL,
    TP_PROV_CODE     VARCHAR(255),
    TP_PHONE         VARCHAR(30),
    TP_FAX           VARCHAR(30),
    TP_EMAIL         VARCHAR(50),
    PERIOD_KIND      VARCHAR(1)   NOT NULL,               -- kieuKy Q/M
    FROM_DT          DATE         NOT NULL,               -- kyKKhaiTuNgay
    TO_DT            DATE         NOT NULL,               -- kyKKhaiDenNgay
    OFFICE_CODE      VARCHAR(10)  NOT NULL,               -- maCQTNoiNop
    OFFICE_NAME      VARCHAR(150) NOT NULL,               -- tenCQTNoiNop
    DECL_DT          DATE         NOT NULL,               -- ngayLapTKhai
    EXT_REASON_CODE  VARCHAR(10),
    EXT_REASON       VARCHAR(255),
    AGENT_NAME       VARCHAR(400),                        -- [06]
    AGENT_TAX_CODE   VARCHAR(14),                         -- [07]
    AGENT_CTR_NO     VARCHAR(100),                        -- [08]
    AGENT_CTR_DT     DATE,
    DU_NAME          VARCHAR(400),                        -- [09]
    DU_TAX_CODE      VARCHAR(14),                         -- [10]
    DU_ADDR          VARCHAR(255),                        -- [11]
    DU_PROV_CODE     VARCHAR(255),                        -- [11c]
    DU_PROV          VARCHAR(255),
    DU_DIST_CODE     VARCHAR(255),                        -- [11b]
    DU_DIST          VARCHAR(255),
    DU_WARD_CODE     VARCHAR(255),                        -- [11a]
    DU_WARD          VARCHAR(255),
    INDICATORS       JSONB        NOT NULL DEFAULT '{}'::jsonb,
    REG_ID           VARCHAR(100),
    REG_DTM          VARCHAR(14)  NOT NULL,
    MOD_ID           VARCHAR(100),
    MOD_DTM          VARCHAR(14)  NOT NULL,
    DEL_YN           VARCHAR(1)   NOT NULL DEFAULT 'N',
    STATUS           VARCHAR(20)  NOT NULL,               -- DRAFT | LOCKED
    CONSTRAINT tax_declarations_pk   PRIMARY KEY (SID),
    CONSTRAINT tax_declarations_uk01 UNIQUE (BIZ_KEY, PERIOD_TYPE, PERIOD_VALUE, PERIOD_YEAR, SUPPL_NO),
    CONSTRAINT tax_declarations_chk01 CHECK (PERIOD_TYPE IN ('month', 'quarter')),
    CONSTRAINT tax_declarations_chk02 CHECK (DECL_TYPE IN ('C', 'B')),
    CONSTRAINT tax_declarations_chk03 CHECK (DEL_YN IN ('Y', 'N'))
);

CREATE INDEX IF NOT EXISTS ix_tax_declarations_biz_period
    ON TAX_DECLARATIONS (BIZ_KEY, PERIOD_YEAR DESC, PERIOD_VALUE DESC);

CREATE TABLE IF NOT EXISTS TAX_DECLARATION_ITEMS (
    ID                     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    VAT_DECL_ID            BIGINT NOT NULL,
    NO_ACTIVITY            NUMERIC(20,6),                 -- ct21
    PREV_CREDIT            NUMERIC(20,6),                 -- ct22
    PURCH_AMT              NUMERIC(20,6),                 -- ct23
    PURCH_AMT_VAT          NUMERIC(20,6),                 -- ct24
    IMP_AMT                NUMERIC(20,6),                 -- ct23a
    IMP_AMT_VAT            NUMERIC(20,6),                 -- ct24a
    DEDUCT_VAT_AMT         NUMERIC(20,6),                 -- ct25
    SALES_AMT_NONDECL      NUMERIC(20,6),                 -- ct26
    TOL_SALES_AMT          NUMERIC(20,6),                 -- ct27
    TOT_SALES_AMT_VAT      NUMERIC(20,6),                 -- ct28
    SALES_AMT_0            NUMERIC(20,6),                 -- ct29
    SALES_AMT_5            NUMERIC(20,6),                 -- ct30
    SALES_AMT_VAT_5        NUMERIC(20,6),                 -- ct31
    SALES_AMT_10           NUMERIC(20,6),                 -- ct32
    SALES_AMT_VAT_10       NUMERIC(20,6),                 -- ct33
    SALES_AMT_NONTAX       NUMERIC(20,6),                 -- ct32a
    SALES_VAT_OTHER        NUMERIC(20,6),                 -- ct33a
    TOTAL_SALES_AMT        NUMERIC(20,6),                 -- ct34
    TOTAL_SALES_AMT_VAT    NUMERIC(20,6),                 -- ct35
    VAT_INCURRED           NUMERIC(20,6),                 -- ct36
    ADJ_DECREASE           NUMERIC(20,6),                 -- ct37
    ADJ_INCREASE           NUMERIC(20,6),                 -- ct38
    TRANSF_VAT             NUMERIC(20,6),                 -- ct39a
    VAT_PAYABLE_ACTIVITY   NUMERIC(20,6),                 -- ct40a
    INVEST_OFFSET_VAT_AMT  NUMERIC(20,6),                 -- ct40b
    VAT_PAYABLE_NET        NUMERIC(20,6),                 -- ct40
    VAT_NOT_DEDUCTED       NUMERIC(20,6),                 -- ct41
    VAT_REFUND_REQ         NUMERIC(20,6),                 -- ct42
    CREDIT_NEXT            NUMERIC(20,6),                 -- ct43
    REG_ID                 VARCHAR(100),
    REG_DTM                VARCHAR(14) NOT NULL,
    MOD_ID                 VARCHAR(100),
    MOD_DTM                VARCHAR(14) NOT NULL,
    DEL_YN                 VARCHAR(1)  NOT NULL DEFAULT 'N',
    CONSTRAINT tax_declaration_items_pk   PRIMARY KEY (ID),
    CONSTRAINT tax_declaration_items_fk01 FOREIGN KEY (VAT_DECL_ID) REFERENCES TAX_DECLARATIONS (SID),
    CONSTRAINT tax_declaration_items_chk01 CHECK (DEL_YN IN ('Y', 'N'))
);

CREATE INDEX IF NOT EXISTS ix_tax_declaration_items_decl
    ON TAX_DECLARATION_ITEMS (VAT_DECL_ID);

-- ============================================================================
-- Annexes (added 2026-07-21) — 4 types confirmed by the PO prototype
-- (VAT_Declaration_Report.html): BKBR 01-1/GTGT, BKMV 01-2/GTGT,
-- ALLOC 01-6/GTGT, REDUCE8 (8% reduction, NQ 204/2025).
-- ============================================================================

-- Header attach-flags (create-form checkboxes).
ALTER TABLE TAX_DECLARATIONS ADD COLUMN IF NOT EXISTS ANNEX_BKBR_YN    VARCHAR(1) NOT NULL DEFAULT 'N';
ALTER TABLE TAX_DECLARATIONS ADD COLUMN IF NOT EXISTS ANNEX_BKMV_YN    VARCHAR(1) NOT NULL DEFAULT 'N';
ALTER TABLE TAX_DECLARATIONS ADD COLUMN IF NOT EXISTS ANNEX_ALLOC_YN   VARCHAR(1) NOT NULL DEFAULT 'N';
ALTER TABLE TAX_DECLARATIONS ADD COLUMN IF NOT EXISTS ANNEX_REDUCE8_YN VARCHAR(1) NOT NULL DEFAULT 'N';

-- Generic annex-line table (one row = one invoice/allocation line).
CREATE TABLE IF NOT EXISTS TAX_DECLARATION_ANNEX_ITEMS (
    ID            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    VAT_DECL_ID   BIGINT       NOT NULL,
    ANNEX_TYPE    VARCHAR(10)  NOT NULL,               -- BKBR | BKMV | ALLOC | REDUCE8
    IO_DV         VARCHAR(1),                          -- I input | O output
    SRC_DOC_ID    VARCHAR(50),                         -- BUSA_DOC_MSTR.DOC_ID; NULL = manual
    INV_NO        VARCHAR(50),
    INV_SYMBOL    VARCHAR(20),
    INV_DT        VARCHAR(8),                          -- YYYYMMDD
    TRCO_TAX_CODE VARCHAR(14),
    TRCO_NM       VARCHAR(400),
    PROD_NM       VARCHAR(300),
    SPLY_AMT      NUMERIC(20,6),
    VAT_RATE      NUMERIC(5,2),
    VAT_AMT       NUMERIC(20,6),
    REDUCED_AMT   NUMERIC(20,6),                       -- REDUCE8 only
    ALLOC_RATIO   NUMERIC(9,6),                        -- ALLOC (01-6) only
    HAND_REG_YN   VARCHAR(1)   NOT NULL DEFAULT 'N',
    DISP_ORD      INTEGER,
    REG_ID        VARCHAR(100),
    REG_DTM       VARCHAR(14)  NOT NULL,
    MOD_ID        VARCHAR(100),
    MOD_DTM       VARCHAR(14)  NOT NULL,
    DEL_YN        VARCHAR(1)   NOT NULL DEFAULT 'N',
    CONSTRAINT tax_declaration_annex_items_pk   PRIMARY KEY (ID),
    CONSTRAINT tax_declaration_annex_items_fk01 FOREIGN KEY (VAT_DECL_ID) REFERENCES TAX_DECLARATIONS (SID),
    CONSTRAINT tax_declaration_annex_items_chk01 CHECK (ANNEX_TYPE IN ('BKBR','BKMV','ALLOC','REDUCE8')),
    CONSTRAINT tax_declaration_annex_items_chk02 CHECK (DEL_YN IN ('Y','N'))
);

CREATE INDEX IF NOT EXISTS ix_tax_declaration_annex_items_decl_type
    ON TAX_DECLARATION_ANNEX_ITEMS (VAT_DECL_ID, ANNEX_TYPE);

package com.kosign.wecms.domain.banking.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.IdClass;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

import java.math.BigDecimal;

/**
 * Mirrors legacy wecmsvndev.ACCT_TRNS_HSTR for the Sprint 1 column
 * subset (Transaction History VND/FCY). The "confirmed" UI flag is
 * derived in service via AcctTrnsRcvPayInfmRepository.existsByPk(...) —
 * see AcctTrnsRcvPayInfmRepository for the rationale.
 *
 * BANK_CD + ACCT_NO are loosely linked to ACCT_MSTR via plain @Column
 * String IDs (no @JoinColumn / cascade) per CLAUDE.md.
 */
@Getter
@Setter
@NoArgsConstructor
@Entity
@Table(name = "ACCT_TRNS_HSTR")
@IdClass(AcctTrnsHstrId.class)
public class AcctTrnsHstr {

    @Id
    @Column(name = "BIZ_KEY", length = 20, nullable = false)
    private String bizKey;

    @Id
    @Column(name = "ACCT_SEQ_NO", length = 20, nullable = false)
    private String acctSeqNo;

    @Column(name = "BANK_CD", length = 20)
    private String bankCd;

    @Column(name = "ACCT_NO", length = 100)
    private String acctNo;

    @Column(name = "TRSC_DT", length = 8)
    private String trscDt;

    @Column(name = "TRSC_TM", length = 6)
    private String trscTm;

    @Column(name = "CCY_CD", length = 3)
    private String ccyCd;

    @Column(name = "INOUT_DV", length = 1)
    private String inoutDv;

    @Column(name = "TRSC_AMT")
    private BigDecimal trscAmt;

    @Column(name = "BAL")
    private BigDecimal bal;

    @Column(name = "RMRK", length = 500)
    private String rmrk;

    @Column(name = "RMRK2", length = 500)
    private String rmrk2;

    @Column(name = "LINK_MATCH_YN", length = 1, nullable = false)
    private String linkMatchYn;

    @Column(name = "BANK_REF_NO", length = 100)
    private String bankRefNo;

    /**
     * SHA-256(bank_cd | trsc_dt | trsc_tm | amt | inout_dv | rmrk | rmrk2),
     * lowercase hex, 64 chars. Generated by
     * {@code BankTrnsIdGenerator.fullId(...)} on sync insert; used as the
     * idempotency key on re-scrape (legacy parity —
     * {@code fnsh_0001_001_c001_act.jsp:170} {@code generateBankTrnsFullId}).
     */
    @Column(name = "BANK_TRNS_FULL_ID", length = 100)
    private String bankTrnsFullId;

    /**
     * {@code trsc_dt + "_" + fullId[0..4]} — human-readable cross-reference
     * shown in audit / matching screens. Deterministic given FULL_ID, so
     * collision retries are unnecessary (legacy parity —
     * {@code fnsh_0001_001_c001_act.jsp:204} {@code generateBankTrnsShortId}).
     */
    @Column(name = "BANK_TRNS_SHORT_ID", length = 20)
    private String bankTrnsShortId;

    /**
     * {@code 'Y'} marks a row whose remarks have been edited by the user;
     * the sync re-scrape MUST NOT overwrite {@code rmrk} / {@code rmrk2} /
     * {@code link_match_yn} on locked rows. Default {@code 'N'} on insert
     * (set by V156 column default at the DB level).
     *
     * <p>{@code @JdbcTypeCode(SqlTypes.CHAR)} — V156 declares the column
     * as {@code CHAR(1)} ({@code bpchar(1)}) for legacy parity (legacy
     * DEV ships {@code LOCKED_YN bpchar(1)}). Without this annotation
     * Hibernate maps {@code String} → {@code VARCHAR(1)} and the
     * schema-validate step fails. Same precedent as
     * {@code SysScrOptionWecms.sortYn} (V38).
     */
    @Column(name = "LOCKED_YN", length = 1, nullable = false)
    @JdbcTypeCode(SqlTypes.CHAR)
    private String lockedYn;

    /**
     * Reporting Account (chart of accounts) assigned to the bank
     * transaction. Mirrors legacy {@code fnsh_0200_001_view.jsp} line 327
     * where the Reporting Account cell reads {@code CHART_ACCT_CD} /
     * {@code CHART_ACCT_SEQ_NO} off the transaction row. Both columns are
     * nullable — unassigned rows render the "Select Account" placeholder.
     *
     * <p>Surrogate FK to {@code CHART_ACCT_INFM} (no DB FK constraint —
     * mirrors legacy parity; the service-layer guard in
     * {@code TransactionService.updateReportingAccount} validates the
     * code exists for the tenant before writing).
     */
    @Column(name = "CHART_ACCT_CD", length = 20)
    private String chartAcctCd;

    @Column(name = "CHART_ACCT_SEQ_NO", length = 10)
    private String chartAcctSeqNo;

    @Column(name = "REG_ID", length = 100)
    private String regId;

    @Column(name = "REG_DTM", length = 14)
    private String regDtm;

    @Column(name = "MOD_ID", length = 100)
    private String modId;

    @Column(name = "MOD_DTM", length = 14)
    private String modDtm;
}

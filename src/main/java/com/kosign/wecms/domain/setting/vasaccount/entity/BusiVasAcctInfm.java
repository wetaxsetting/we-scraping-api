package com.kosign.wecms.domain.setting.vasaccount.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.IdClass;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

/**
 * Settings &gt; VAS Account — per-tenant accounting code list used to tag
 * bank accounts and transactions. Mirrors legacy
 * {@code WECMS DEV/WECMS/src/wabooks/entity/BusiVasAcctInfm.java} +
 * {@code IDO.BUSI_VAS_ACCT_INFM_R001} column-for-column (13 columns).
 *
 * <p>This entity intentionally does <b>not</b> extend
 * {@link com.kosign.wecms.common.entity.BaseEntity} — that superclass
 * declares audit columns as {@code OffsetDateTime}, but the DEV schema
 * stores {@code REG_DTM}/{@code MOD_DTM} as {@code VARCHAR(14)}
 * ({@code yyyyMMddHHmmss}). Mirrors the {@code ErpTrnsHstr} pattern. The
 * service writes the legacy-format timestamp string at create / update
 * time.
 *
 * <p>{@code VAS_ACCT_TYPE}, {@code STTS}, {@code DEL_YN} are {@code CHAR(1)}
 * on disk; {@link JdbcTypeCode @JdbcTypeCode(SqlTypes.CHAR)} keeps Hibernate's
 * {@code ddl-auto = validate} happy (same approach as {@code ErpTrnsHstr.erpType}
 * and {@code SysScrOptionWecms.sortYn}).
 *
 * <p>Tenant scoping: {@code bizKey} is the first PK component and the
 * service applies it as a predicate on every query — never trust a wire
 * {@code biz_key}; always read it from {@link
 * com.kosign.wecms.common.tenant.TenantContext#currentBizKey()}.
 */
@Getter
@Setter
@NoArgsConstructor
@Entity
@Table(name = "BUSI_VAS_ACCT_INFM")
@IdClass(BusiVasAcctInfmId.class)
public class BusiVasAcctInfm {

    /** Tenant key. Part of every WHERE clause; never exposed on the wire. */
    @Id
    @Column(name = "BIZ_KEY", length = 20, nullable = false)
    private String bizKey;

    /** Per-tenant monotonic sequence. DEV stores {@code NUMERIC(10,0)};
     *  refactor-local stores {@code BIGINT} (V77 hotfix — same Hibernate
     *  validator trade-off as V75 for {@code ErpTrnsHstr.seqNo}).
     *  Generated by {@link com.kosign.wecms.domain.setting.vasaccount.service.VasAcctSeqNoGenerator}
     *  (Java-side, MAX+1) — refactor preference over the legacy
     *  {@code wb_get_next_val} branch. */
    @Id
    @Column(name = "VAS_ACCT_SEQ_NO", nullable = false)
    private Long vasAcctSeqNo;

    /** Short numeric code (the "VAS code", e.g. {@code 111}) — tenant-unique
     *  while {@code DEL_YN='N'}. Service enforces; no DB UNIQUE constraint
     *  (DEV matches). */
    @Column(name = "VAS_ACCT_CD", length = 15, nullable = false)
    private String vasAcctCd;

    /** Display name (often the localised accounting-row label). DEV allows
     *  NULL though every real row has a value — refactor preserves the
     *  nullability for parity. */
    @Column(name = "VAS_ACCT_NM", length = 50)
    private String vasAcctNm;

    /** Optional English display name. */
    @Column(name = "VAS_ACCT_ENM", length = 50)
    private String vasAcctEnm;

    /** {@code 0} Dual / {@code 1} Credit / {@code 2} Debit. Service maps
     *  via {@link com.kosign.wecms.common.enums.VasAcctType#fromCode(String)}. */
    @Column(name = "VAS_ACCT_TYPE", length = 1, nullable = false)
    @JdbcTypeCode(SqlTypes.CHAR)
    private String vasAcctType;

    /** {@code A} Active / {@code I} Inactive. Service maps via
     *  {@link com.kosign.wecms.common.enums.AStts#fromCode(String)}. */
    @Column(name = "STTS", length = 1, nullable = false)
    @JdbcTypeCode(SqlTypes.CHAR)
    private String stts;

    /** Optional notes / description. DB cap is 200; service enforces. */
    @Column(name = "CONT", length = 200)
    private String cont;

    /** Soft-delete flag — {@code N} live / {@code Y} deleted. DB default
     *  is {@code 'N'} per V77; service writes the value explicitly on
     *  every create + soft-delete. */
    @Column(name = "DEL_YN", length = 1, nullable = false)
    @JdbcTypeCode(SqlTypes.CHAR)
    private String delYn;

    /** Audit — original creator id. Set once at create time. */
    @Column(name = "REG_ID", length = 100, nullable = false, updatable = false)
    private String regId;

    /** Audit — original creation timestamp, {@code yyyyMMddHHmmss} UTC. */
    @Column(name = "REG_DTM", length = 14, nullable = false, updatable = false)
    private String regDtm;

    /** Audit — last modifier id. Service rewrites on every update +
     *  soft-delete. */
    @Column(name = "MOD_ID", length = 100, nullable = false)
    private String modId;

    /** Audit — last modification timestamp, {@code yyyyMMddHHmmss} UTC. */
    @Column(name = "MOD_DTM", length = 14, nullable = false)
    private String modDtm;
}

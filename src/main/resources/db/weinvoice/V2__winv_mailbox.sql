-- ---------------------------------------------------------------------------
-- WINV_MLBX_INFM — mailboxes a user connects so the engine collects invoice mail
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS weinvoice.winv_mlbx_infm (
	mlbx_seq       bigint        GENERATED BY DEFAULT AS IDENTITY,
	owner_id       varchar(100)  NOT NULL,
	mlbx_kind      varchar(10)   NOT NULL,
	mail_addr      varchar(320)  NOT NULL,
	auth_type      varchar(20)   NOT NULL,
	imap_host      varchar(255)  NULL,
	imap_port      int           NULL,
	tls_mode       varchar(10)   NULL,
	login_id       varchar(320)  NOT NULL,
	secret_enc     text          NOT NULL,
	fldr_list      varchar(500)  NOT NULL DEFAULT 'INBOX',
	cmpn_scope     varchar(5)    NOT NULL DEFAULT 'ONE',
	cmpn_mst       varchar(14)   NULL,
	conn_stts      varchar(20)   NOT NULL DEFAULT 'CONNECTED',
	conn_msg       varchar(500)  NULL,
	last_scan_dtm  varchar(14)   NULL,
	last_scan_cnt  int           NULL,
	del_yn         bpchar(1)     NOT NULL DEFAULT 'N',
	reg_id         varchar(100)  NOT NULL,
	reg_dtm        varchar(14)   NOT NULL,
	mod_id         varchar(100)  NULL,
	mod_dtm        varchar(14)   NULL,
	CONSTRAINT winv_mlbx_infm_pk    PRIMARY KEY (mlbx_seq),
	CONSTRAINT winv_mlbx_infm_chk01 CHECK ((mlbx_kind = ANY (ARRAY['GMAIL', 'MICROSOFT', 'IMAP']))),
	CONSTRAINT winv_mlbx_infm_chk02 CHECK ((auth_type = ANY (ARRAY['APP_PASSWORD', 'PASSWORD', 'OAUTH_MS']))),
	CONSTRAINT winv_mlbx_infm_chk03 CHECK ((tls_mode IS NULL OR tls_mode = ANY (ARRAY['SSL', 'STARTTLS']))),
	CONSTRAINT winv_mlbx_infm_chk04 CHECK ((cmpn_scope = ANY (ARRAY['ONE', 'ALL']))),
	CONSTRAINT winv_mlbx_infm_chk05 CHECK ((cmpn_scope = 'ALL' OR cmpn_mst IS NOT NULL)),
	CONSTRAINT winv_mlbx_infm_chk06 CHECK ((conn_stts = ANY (ARRAY['CONNECTED', 'ERROR', 'EXPIRED']))),
	CONSTRAINT winv_mlbx_infm_chk07 CHECK ((del_yn = ANY (ARRAY['Y'::bpchar, 'N'::bpchar]))),
	CONSTRAINT winv_mlbx_infm_chk08 CHECK ((imap_port IS NULL OR imap_port BETWEEN 1 AND 65535))
);

COMMENT ON TABLE  weinvoice.winv_mlbx_infm IS 'Mailbox (Gmail, Microsoft 365, company IMAP) a WeInvoice user (WeCMS USER_ID) connects; the engine scans it read-only for invoice mail (XML / PDF / links) of the user''s tax codes.';
COMMENT ON COLUMN weinvoice.winv_mlbx_infm.mlbx_seq      IS 'Mailbox id (API id, sent as a string).';
COMMENT ON COLUMN weinvoice.winv_mlbx_infm.mlbx_kind     IS 'GMAIL | MICROSOFT | IMAP (company mail).';
COMMENT ON COLUMN weinvoice.winv_mlbx_infm.auth_type     IS 'APP_PASSWORD (Gmail) | PASSWORD (IMAP) | OAUTH_MS (Microsoft refresh token).';
COMMENT ON COLUMN weinvoice.winv_mlbx_infm.imap_host     IS 'IMAP server. Filled by the backend for GMAIL (imap.gmail.com) and MICROSOFT (outlook.office365.com).';
COMMENT ON COLUMN weinvoice.winv_mlbx_infm.tls_mode      IS 'SSL (implicit TLS, usually 993) | STARTTLS.';
COMMENT ON COLUMN weinvoice.winv_mlbx_infm.login_id      IS 'IMAP login. Defaults to mail_addr.';
COMMENT ON COLUMN weinvoice.winv_mlbx_infm.secret_enc    IS 'Password / app password / Microsoft refresh token: "v1:" + base64(iv(12) || AES-256-GCM ciphertext+tag) under WECMS_WEINVOICE_SECRET_KEY (same cipher as winv_cmpn_infm.gdt_pw_enc). Empty string after a soft delete. Never returned by the API.';
COMMENT ON COLUMN weinvoice.winv_mlbx_infm.fldr_list     IS 'IMAP folders to scan, comma separated (default INBOX).';
COMMENT ON COLUMN weinvoice.winv_mlbx_infm.cmpn_scope    IS 'ONE = invoices of cmpn_mst only; ALL = every non-deleted tax code of the owner (winv_cmpn_infm).';
COMMENT ON COLUMN weinvoice.winv_mlbx_infm.conn_stts     IS 'CONNECTED; ERROR = the mail server refused the last login (conn_msg); EXPIRED = Microsoft refresh token revoked or expired.';
COMMENT ON COLUMN weinvoice.winv_mlbx_infm.last_scan_dtm IS 'End of the last engine scan, yyyyMMddHHmmss (UTC, house convention of every *_dtm column).';
COMMENT ON COLUMN weinvoice.winv_mlbx_infm.last_scan_cnt IS 'Invoices that got a file (XML / PDF) from the last scan.';
COMMENT ON COLUMN weinvoice.winv_mlbx_infm.del_yn        IS 'Y = disconnected by the owner (soft delete, secret erased).';

-- Re-connecting the same address updates the active row (ON CONFLICT target of the backend).
CREATE UNIQUE INDEX IF NOT EXISTS winv_mlbx_infm_uk01
	ON weinvoice.winv_mlbx_infm (owner_id, lower(mail_addr))
	WHERE del_yn = 'N';

CREATE INDEX IF NOT EXISTS winv_mlbx_infm_ix01
	ON weinvoice.winv_mlbx_infm (owner_id)
	WHERE del_yn = 'N';

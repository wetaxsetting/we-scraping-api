-- ============================================================================
-- V1__auth_schema.sql
-- Login-related tables for the WeCMS Spring Boot R&D refactor.
-- Names and fields preserved from the legacy JEX schema; columns limited to
-- those the login flow actually uses (see docs/task-refactor-the-login-wild-bird.md).
-- ============================================================================

-- Company / tenant master (minimal subset)
CREATE TABLE BUSI_INFM (
    BIZ_KEY     VARCHAR(32)  NOT NULL,
    BUSI_NM     VARCHAR(200) NOT NULL,
    NTNL_CD     VARCHAR(2)   NOT NULL DEFAULT 'VN',
    BUSI_STTS   VARCHAR(2)   NOT NULL DEFAULT 'N',  -- N = NORMAL
    REG_USER    VARCHAR(50),
    REG_DTM     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MOD_USER    VARCHAR(50),
    MOD_DTM     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_BUSI_INFM PRIMARY KEY (BIZ_KEY)
);

-- User master
CREATE TABLE USER_INFM (
    USER_ID     VARCHAR(50)  NOT NULL,
    USER_NM     VARCHAR(100) NOT NULL,
    USER_PW     VARCHAR(100) NOT NULL,          -- BCrypt hash
    EML         VARCHAR(200),
    ACTV_YN     CHAR(1)      NOT NULL DEFAULT 'Y',
    LOCK_YN     CHAR(1)      NOT NULL DEFAULT 'N',
    DEL_YN      CHAR(1)      NOT NULL DEFAULT 'N',
    LANG_CD     VARCHAR(2)   NOT NULL DEFAULT 'EN',
    REG_USER    VARCHAR(50),
    REG_DTM     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MOD_USER    VARCHAR(50),
    MOD_DTM     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_USER_INFM      PRIMARY KEY (USER_ID),
    CONSTRAINT CK_USER_INFM_ACTV CHECK (ACTV_YN IN ('Y','N')),
    CONSTRAINT CK_USER_INFM_LOCK CHECK (LOCK_YN IN ('Y','N')),
    CONSTRAINT CK_USER_INFM_DEL  CHECK (DEL_YN  IN ('Y','N'))
);

-- User ↔ company mapping (multi-tenant linkage)
CREATE TABLE USER_BUSI_CONN_INFM (
    USER_ID         VARCHAR(50) NOT NULL,
    BIZ_KEY         VARCHAR(32) NOT NULL,
    EMPL_NO         VARCHAR(30),
    LST_LGN_DATE    TIMESTAMPTZ,
    DEL_YN          CHAR(1)     NOT NULL DEFAULT 'N',
    REG_USER        VARCHAR(50),
    REG_DTM         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MOD_USER        VARCHAR(50),
    MOD_DTM         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_USER_BUSI_CONN_INFM PRIMARY KEY (USER_ID, BIZ_KEY),
    CONSTRAINT FK_UBCI_USER  FOREIGN KEY (USER_ID) REFERENCES USER_INFM (USER_ID),
    CONSTRAINT FK_UBCI_BUSI  FOREIGN KEY (BIZ_KEY) REFERENCES BUSI_INFM (BIZ_KEY),
    CONSTRAINT CK_UBCI_DEL   CHECK (DEL_YN IN ('Y','N'))
);

CREATE INDEX IX_USER_BUSI_CONN_INFM_USER ON USER_BUSI_CONN_INFM (USER_ID) WHERE DEL_YN = 'N';

-- Login audit log
CREATE TABLE USER_LOGIN_HIS (
    USER_ID     VARCHAR(50)  NOT NULL,
    REG_DTM     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    IP_ADDR     VARCHAR(100),
    LGN_CHNL    VARCHAR(3)   NOT NULL,       -- PC | MOB
    RSLT_CD     VARCHAR(10)  NOT NULL,       -- SUCCESS | FAIL
    RSLT_CONT   VARCHAR(200),
    CONSTRAINT PK_USER_LOGIN_HIS PRIMARY KEY (USER_ID, REG_DTM),
    CONSTRAINT CK_USER_LOGIN_HIS_CHNL CHECK (LGN_CHNL IN ('PC','MOB')),
    CONSTRAINT CK_USER_LOGIN_HIS_RSLT CHECK (RSLT_CD IN ('SUCCESS','FAIL'))
);

CREATE INDEX IX_USER_LOGIN_HIS_RSLT ON USER_LOGIN_HIS (USER_ID, RSLT_CD, REG_DTM DESC);
